// Rejects comments and test modifiers that silence a check instead of fixing
// the code, and non-null assertions in Vue templates, which Oxlint skips.
// This runs outside Oxlint and ESLint so an inline disable comment cannot
// switch it off.
import { readdirSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const roots = ["apps", "packages", "tooling", "scripts"];
const skipped = new Set([
  "node_modules",
  "dist",
  ".histoire",
  "test-results",
  "playwright-report",
  "coverage",
  ".features-gen",
]);
// Generated by the router plugin; regenerated rather than edited.
const generated = new Set(["apps/workout/src/route-map.d.ts"]);
const self = "tooling/lint/no-suppressions.mjs";

const source = /\.(?:[cm]?[jt]s|vue)$/;
const suppression =
  /(?:eslint|oxlint)-disable|@ts-(?:ignore|nocheck|expect-error)/;
const focusedOrSkipped =
  /\b(?:it|test|describe|Scenario|Given|When|Then)\s*\.\s*(?:only|skip|fixme|todo)\s*\(/;
const gherkinTag = /^\s*@(?:only|skip|fixme)\b/;
// Oxlint checks script blocks; Vue template expressions need this check.
const nonNullAssertion = /[\w\])]!(?=[.[)])/;

function* files(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (skipped.has(entry.name)) continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) yield* files(path);
    else yield path;
  }
}

function check(path, text) {
  const isTest = /(?:^|\/)test\//.test(path);
  const problems = [];
  for (const [index, line] of text.split("\n").entries()) {
    const at = `${path}:${index + 1}`;
    if (source.test(path) && suppression.test(line))
      problems.push(
        `${at}: suppression comment. Fix the code instead of disabling the check.`,
      );
    if (isTest && source.test(path) && focusedOrSkipped.test(line))
      problems.push(
        `${at}: focused or skipped test. Fix or delete the test explicitly.`,
      );
    if (path.endsWith(".vue") && !isTest && nonNullAssertion.test(line))
      problems.push(
        `${at}: non-null assertion. Handle the missing value explicitly.`,
      );
    if (path.endsWith(".feature") && gherkinTag.test(line))
      problems.push(`${at}: focused or skipped scenario tag.`);
  }
  return problems;
}

const problems = [];
for (const top of roots)
  for (const absolute of files(join(root, top))) {
    const path = relative(root, absolute);
    if (generated.has(path) || path === self) continue;
    if (!source.test(path) && !path.endsWith(".feature")) continue;
    problems.push(...check(path, readFileSync(absolute, "utf8")));
  }

if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}
